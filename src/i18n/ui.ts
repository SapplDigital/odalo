type Plain = Record<string, unknown>;
const merge = (base: Plain, over: Plain): Plain => {
  const out: Plain = { ...base };
  for (const [k, v] of Object.entries(over)) out[k] = v && typeof v === 'object' && !Array.isArray(v) && base[k] && typeof base[k] === 'object' && !Array.isArray(base[k]) ? merge(base[k] as Plain, v as Plain) : v;
  return out;
};
