/** Accented letters: base glyph plus a mark: [base, mark row, mark drawing]. */
const MARKS: Record<string, [string, number, string]> = {
  á: ['a', 1, '...#.'], é: ['e', 1, '...#.'], ó: ['o', 1, '...#.'], ú: ['u', 1, '...#.'],
  ä: ['a', 1, '.#.#.'], ö: ['o', 1, '.#.#.'], ü: ['u', 1, '.#.#.'],
  ñ: ['n', 0, '.##.#|#.##.'],
};

function grid(c: string): string[] | null {
  const s = MARKS[c];
  const g = GLYPHS[s ? s[0] : c];
  if (!g) return null;
  const width = g.rows[0].length;
  const rows = Array.from({ length: HEIGHT }, () => '.'.repeat(width));
  g.rows.forEach((r, i) => (rows[(g.from ?? 1) + i] = r));
  if (s) s[2].split('|').forEach((r, i) => (rows[s[1] + i] = r.padEnd(width, '.').slice(0, width)));
  return rows;
}

function lineCells(text: string) {
  const cells: [number, number][] = [];
  let x = 0;
  for (const c of [...text]) {
    if (/\s/.test(c)) { x += SPACE; continue; }
    const r = grid(c) ?? grid(c.toLowerCase()) ?? grid(c.toUpperCase());
    if (!r) { x += SPACE; continue; }
    r.forEach((f, y) => [...f].forEach((v, cx) => v === '#' && cells.push([x + cx, y])));
    x += r[0].length + GAP;
  }
  return { cells, width: Math.max(0, x - GAP) };
}

/** Dot cells of a single line, doubled with Scale2x: { cols, rows, cells: [col,row][] }. */
export function dotCells(text: string) {
  const { cells, width } = lineCells(text);
  const W = width + 2;
  const H = HEIGHT + 2;
  const g = new Uint8Array(W * H);
  for (const [x, y] of cells) g[(y + 1) * W + x + 1] = 1;
  const v = (x: number, y: number) => g[y * W + x];
  const out: [number, number][] = [];
  for (let y = 1; y < H - 1; y++)
    for (let x = 1; x < W - 1; x++) {
      const P = v(x, y), A = v(x, y - 1), B = v(x + 1, y), C = v(x - 1, y), D = v(x, y + 1);
      const e0 = C === A && C !== D && A !== B ? A : P;
      const e1 = A === B && A !== C && B !== D ? B : P;
      const e2 = D === C && D !== B && C !== A ? C : P;
      const e3 = B === D && B !== A && D !== C ? D : P;
      const bx = (x - 1) * 2, by = (y - 1) * 2;
      if (e0) out.push([bx, by]);
      if (e1) out.push([bx + 1, by]);
      if (e2) out.push([bx, by + 1]);
      if (e3) out.push([bx + 1, by + 1]);
    }
  return { cols: width * 2, rows: HEIGHT * 2, cells: out };
}

/** Several lines stacked (line gap = 1 source row, as in the original): { cols, rows, cells }. */
export function dotLines(lines: string[]) {
  const cells: [number, number][] = [];
  let cols = 0;
  lines.forEach((l, i) => {
    const r = dotCells(l.trim());
    cols = Math.max(cols, r.cols);
    for (const [x, y] of r.cells) cells.push([x, y + i * (HEIGHT + 1) * 2]);
  });
  return { cols, rows: ((lines.length - 1) * (HEIGHT + 1) + HEIGHT) * 2, cells };
}
